export function coverageForPath(path: string): GulfCoverageCountry | null {
  if (path === '/cytotec-saudi-arabia' || path.startsWith('/cytotec-') && [
    'riyadh', 'jeddah', 'makkah', 'madinah', 'dammam', 'khobar', 'taif', 'tabuk',
    'abha', 'jazan', 'buraydah', 'ahsa', 'khamis-mushait', 'qatif'
  ].some((slug) => path === `/cytotec-${slug}`)) return GULF_COVERAGE.find((x) => x.key === 'saudi') || null;
  if (path === '/cytotec-uae') return GULF_COVERAGE.find((x) => x.key === 'uae') || null;
  if (path === '/cytotec-kuwait') return GULF_COVERAGE.find((x) => x.key === 'kuwait') || null;
  if (path === '/cytotec-bahrain') return GULF_COVERAGE.find((x) => x.key === 'bahrain') || null;
  return null;
}
